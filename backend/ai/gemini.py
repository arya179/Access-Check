import os
import json
import logging
from typing import Dict, Any, List, Optional
from backend.core.config import settings
from backend.ai.client import ai_client

logger = logging.getLogger(__name__)

class GemmaRemediator:
    """
    AI Remediation engine powered by Gemma 4 (gemma-4-26b-a4b-it) using the official google-genai SDK.
    Provides actionable code fixes, WCAG compliance explanations,
    and developer guidance for real accessibility violations found by axe-core.
    """
    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.model = settings.GEMMA_MODEL or "gemma-4-26b-a4b-it"

    async def generate_remediations(
        self,
        url: str,
        violations: List[Dict[str, Any]],
        model_override: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates remediation guides and fixes for accessibility violations using Gemma 4.
        If no API key is provided or AI is unavailable, returns helpful standard best-practice guides
        without faking AI responses.
        """
        if not ai_client.client or not self.api_key:
            return {
                "ai_summary": "Google GenAI API key not configured. Showing standard WCAG guidelines. Provide GEMINI_API_KEY in .env for AI-powered automated code remediation using Gemma 4.",
                "remediations": {
                    v["id"]: f"**Rule {v['id']} Remediation**:\n{v['help']}. Reference: {v['helpUrl']}\n\nEnsure semantic HTML tags, suitable ARIA attributes, and accessible color contrast ratios are used."
                    for v in violations
                }
            }

        try:
            # Prepare summary of top violations for Gemma 4
            items_to_analyze = violations[:10]  # Focus on key violations to keep prompt concise
            prompt_payload = []
            for item in items_to_analyze:
                sample_html = item.get("nodes", [{}])[0].get("html", "") if item.get("nodes") else ""
                prompt_payload.append({
                    "id": item["id"],
                    "impact": item.get("impact"),
                    "description": item.get("description"),
                    "sample_element": sample_html[:200],
                    "failure": item.get("nodes", [{}])[0].get("failureSummary", "") if item.get("nodes") else ""
                })

            prompt = f"""You are an expert accessibility engineer and full-stack developer auditing: {url}

Analyze these accessibility violations found by Axe-core:
{json.dumps(prompt_payload, indent=2)}

Please provide:
1. An overall executive accessibility summary (2-3 sentences).
2. For each violation id, provide a clear, actionable developer code fix (showing standard Before/After or exact HTML/JSX/CSS adjustments) and explain how it solves the WCAG criterion.

Return your response in valid JSON with this exact structure:
{{
  "summary": "executive summary text",
  "remediations": {{
     "<violation_id>": "Markdown formatted code fix and explanation"
  }}
}}
"""
            data = await ai_client.generate_json(prompt, timeout=15.0)
            return {
                "ai_summary": data.get("summary", "AI remediation generated by Gemma 4."),
                "remediations": data.get("remediations", {})
            }

        except Exception as e:
            logger.error(f"Error calling Gemma 4 AI: {e}")
            return {
                "ai_summary": f"Gemma 4 AI remediation unavailable: {str(e)}",
                "remediations": {
                    v["id"]: f"Rule: {v['help']}. Consult official specs: {v['helpUrl']}"
                    for v in violations
                }
            }


